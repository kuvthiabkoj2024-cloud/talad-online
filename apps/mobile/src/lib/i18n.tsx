export type Strings = (typeof STRINGS)['lo'];

const LocaleContext = createContext<{ locale: Locale; t: Strings; setLocale: (l: Locale) => void }>({
  locale: DEFAULT_LOCALE,
  t: STRINGS[DEFAULT_LOCALE],
  setLocale: () => {},
});

const KEY = 'mcmart.locale';

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(DEFAULT_LOCALE);
  useEffect(() => {
    void storage.get(KEY).then((v) => (v === 'lo' || v === 'en') && setLocaleState(v));
  }, []);
  const setLocale = (l: Locale) => {
    setLocaleState(l);
    void storage.set(KEY, l);
  };
  return <LocaleContext value={{ locale, t: STRINGS[locale], setLocale }}>{children}</LocaleContext>;
}

export const useI18n = () => useContext(LocaleContext);

/** "{n} sold" → "12 sold". */
export const fill = (template: string, values: Record<string, string | number>) =>
  template.replace(/\{(\w+)\}/g, (_, k: string) => String(values[k] ?? ''));
