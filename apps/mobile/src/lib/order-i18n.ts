const STRINGS = { lo, en };

/** `o`: the order texts in the app's language. */
export function useOrderI18n() {
  const { locale } = useI18n();
  return { o: STRINGS[locale], locale };
}

/** A cart/checkout API error code in words. */
export function orderError(o: OrderStrings, code: string | undefined): string {
  return (code && (o.cartErrors as Record<string, string>)[code]) || o.cartErrors.generic;
}
