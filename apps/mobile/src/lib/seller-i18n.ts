const STRINGS = { lo, en };

/** The seller screens' words in the app's language. */
export function useSellerI18n() {
  const { locale, t } = useI18n();
  return { s: STRINGS[locale], t, locale };
}

/** The message for an API error code, or the generic one. */
export function sellerError(s: SellerStrings, code: string | undefined): string {
  return (code && s.orders.errors[code]) || s.common.saveError;
}
